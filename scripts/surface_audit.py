#!/usr/bin/env python3
"""Every published output is read by a page, published as a download, or
declared internal with a reason; nothing is invisible by accident.

Ported in spirit from pricephillips/data-center-map visibility_audit.py and
configs/surfaces.json (not imported). That repository found itself with over a
hundred generated outputs and seven pages reading eight of them, and no record
of which of the rest were meant to be internal. The declaration lives in
config/surfaces.json; this module checks it both ways:

  unclassified   a tracked file under data/processed, data/db or
                 data/snapshots that no page reads (by literal path or a
                 declared prefix) and no downloads or internal entry explains
  stale entry    a declared read, download or internal file that is not in
                 the repository, or a declared page read whose path the page
                 code no longer names, either as a literal or through a
                 directory it composes paths from ('./data/processed/' +
                 name, './data/db/' + file)
  wrong layer    a declared read of a file that is not tracked (a page
                 reading something the build does not publish)

Writes docs/surfaces.md, the matrix of outputs by surface, and exits 1 on any
finding. tests/test_surface_audit.py runs it, and validate.yml runs it in CI.

Usage
  python scripts/surface_audit.py            report, write docs/surfaces.md, exit 1 on findings
  python scripts/surface_audit.py --check    report only; write nothing
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT  # noqa: E402

CONFIG = ROOT / "config" / "surfaces.json"
REPORT = ROOT / "docs" / "surfaces.md"
OUTPUT_DIRS = ("data/processed", "data/db", "data/snapshots")
_PATH = re.compile(r"\./(data/[A-Za-z0-9_./-]+)")


def tracked_outputs(root: Path = ROOT) -> list[str]:
    out = subprocess.run(["git", "ls-files", *OUTPUT_DIRS], cwd=root, capture_output=True, text=True, check=True)
    return sorted(line.strip() for line in out.stdout.splitlines() if line.strip())


def page_paths(page: Path) -> set[str]:
    """Every './data/...' string a page's code names, with the './' dropped."""
    return set(_PATH.findall(page.read_text(encoding="utf-8"))) if page.exists() else set()


def names(path: str, named: set[str]) -> bool:
    """Whether page code names a path: the literal, or a directory above it
    that the code composes paths from (a named 'data/db/' covers
    'data/db/parquet/x.parquet' and 'data/db/parquet/')."""
    if path in named:
        return True
    parts = path.rstrip("/").split("/")
    return any("/".join(parts[:i]) + "/" in named for i in range(1, len(parts)))


def audit(config: dict, outputs: list[str], page_text_paths: dict[str, set[str]]) -> tuple[dict, list[str]]:
    """(matrix: output -> [surfaces or disposition], findings)."""
    matrix: dict[str, list[str]] = {o: [] for o in outputs}
    findings: list[str] = []
    tracked = set(outputs)
    for page, spec in config.get("pages", {}).items():
        named = page_text_paths.get(page, set())
        for path in spec.get("reads", []):
            if not names(path, named):
                findings.append(f"stale entry: {page} is declared to read {path} but its code never names it")
            if path in matrix:
                matrix[path].append(page)
            elif path.startswith(OUTPUT_DIRS):
                findings.append(f"wrong layer: {page} reads {path}, which the build does not publish (not tracked)")
        for prefix in spec.get("prefixes", {}):
            if not names(prefix, named):
                findings.append(f"stale entry: {page} is declared to read under {prefix} but its code never names it")
            for o in outputs:
                if o.startswith(prefix):
                    matrix[o].append(page)
    for kind in ("downloads", "internal"):
        for path, reason in config.get(kind, {}).items():
            if path.startswith("_"):
                continue
            if path not in tracked:
                findings.append(f"stale entry: {kind} lists {path}, which is not in the repository")
                continue
            matrix[path].append(f"{kind}: {reason}")
    for o, readers in matrix.items():
        if not readers:
            findings.append(f"unclassified: {o} is published but no page reads it and no entry says what it is for")
    return matrix, findings


def render(matrix: dict, findings: list[str], config: dict) -> str:
    lines = ["# Surfaces: who reads each published output", "",
             "Generated by `scripts/surface_audit.py` from `config/surfaces.json` and the page code; do not edit.",
             "Every tracked file under `data/processed/`, `data/db/` and `data/snapshots/` is read by a page,",
             "published as a download, or internal with a reason.", ""]
    for page, spec in config.get("pages", {}).items():
        lines.append(f"- `{page}`: {spec.get('what', '')}")
    lines += ["", "| Output | Read by, or what it is for |", "|---|---|"]
    for o in sorted(matrix):
        lines.append(f"| `{o}` | {'; '.join(matrix[o]) or 'UNCLASSIFIED'} |")
    lines += ["", f"{len(matrix)} outputs; {len(findings)} finding(s)."]
    if findings:
        lines += [""] + [f"- {f}" for f in findings]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="report only; write nothing")
    args = ap.parse_args(argv)
    config = json.loads(CONFIG.read_text(encoding="utf-8"))
    outputs = tracked_outputs()
    texts = {page: page_paths(ROOT / page) for page in config.get("pages", {})}
    matrix, findings = audit(config, outputs, texts)
    for f in findings:
        print(f"surface audit: {f}")
    print(f"surface audit: {len(outputs)} tracked outputs, {len(findings)} finding(s)")
    if not args.check:
        REPORT.write_text(render(matrix, findings, config), encoding="utf-8")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
