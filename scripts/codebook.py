#!/usr/bin/env python3
"""docs/codebook.md, generated from the constants the code itself runs on.

Modelled on pricephillips/data-center-map CODEBOOK.md, which build_clean_feed.py
regenerates from its classifier tables on every run (docs/pipeline_comparison.md,
"Recommended next" item 7); copied in spirit, not imported. The rubrics here
lived in README.md and module docstrings, so a rule change in code and the
words describing it could drift apart. This module renders the vocabularies,
severity rules, QC checks, counting rules and thresholds from the modules
that apply them, so the codebook cannot say something the code does not do.

Severity rules are shown as truth tables produced by calling the scoring
functions (build_sabin_seeds.restriction_severity, project_severity) on fixed
probe inputs, so a change to a threshold changes the table.

Writes docs/codebook.md (a build stage in scripts/run_pipeline.py, committed
by build-data.yml). tests/test_codebook.py fails when the committed file is
out of date, so a rule change is committed together with its codebook.

Usage
  python scripts/codebook.py            write docs/codebook.md
  python scripts/codebook.py --check    exit 1 if docs/codebook.md is out of date
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_sabin_seeds as sabin  # noqa: E402
import build_seed_outputs as bso  # noqa: E402
import classify  # noqa: E402
import headline_metrics as hm  # noqa: E402
import negative_checks as nc  # noqa: E402
import promote_reviewed as pr  # noqa: E402
import qc_gate  # noqa: E402
import resolutions  # noqa: E402
import verification_worklist as vw  # noqa: E402
from common import ROOT  # noqa: E402

CODEBOOK_PATH = ROOT / "docs" / "codebook.md"

# (label, mechanism types, technology, status, text) probes for the restriction
# severity rule. Each line of the table is what the rule returns for one.
SEVERITY_PROBES = [
    ("Ban or prohibition", {"ban"}, "solar", "active", ""),
    ("Ban or moratorium, source does not say which, in force", {"ban_or_moratorium"}, "solar", "active", ""),
    ("Moratorium in force", {"moratorium"}, "solar", "active", ""),
    ("Moratorium, extended", {"moratorium"}, "wind", "extended", ""),
    ("Moratorium, pending", {"moratorium"}, "solar", "pending", ""),
    ("Wind setback of half a mile", {"setback"}, "wind", "active", "Turbines 2,640 feet from property lines."),
    ("Wind setback of 5x turbine height", {"setback"}, "wind", "active", "Setback 5 times the turbine tip height."),
    ("Wind setback of 1,500 feet", {"setback"}, "wind", "active", "Turbines 1,500 feet from property lines."),
    ("Wind height limit", {"height_limit"}, "wind", "active", "Height limited to 300 feet."),
    ("Wind noise limit of 35 dBA", {"noise_limit"}, "wind", "active", "40 dBA by day and 35 dBA at night."),
    ("Wind noise limit of 45 dBA", {"noise_limit"}, "wind", "active", "45 dBA at the property line."),
    ("Solar setback of 1,000 feet", {"setback"}, "solar", "active", "Panels 1,000 feet from dwellings."),
    ("Solar setback of 500 feet", {"setback"}, "solar", "active", "Panels 500 feet from dwellings."),
    ("Battery storage setback of 1,000 feet", {"setback"}, "battery_storage", "active",
     "Batteries 1,000 feet from dwellings."),
    ("Size cap", {"size_cap"}, "solar", "active", "No project over 50 acres."),
    ("Zoning restriction", {"zoning_restriction"}, "solar", "active", ""),
    ("Any restricting mechanism, pending", {"setback"}, "solar", "pending", "Panels 1,000 feet from dwellings."),
]


def _table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def _code(items) -> str:
    return ", ".join(f"`{i}`" for i in items)


def _lines(items) -> list[str]:
    return [f"- {line}" for line in items]


def render() -> str:
    L = ["# Codebook", "",
         "Generated by `scripts/codebook.py` from the constants the pipeline runs on; do not edit.",
         "Rebuilt on every data build. `README.md` explains the rules in prose; this file is what the",
         "code does. A table that disagrees with the README means the README is out of date.", ""]

    L += ["## Entities", "", "Seed file per entity and the fields every row must have before the build accepts",
          "it (`scripts/build_seed_outputs.py`).", ""]
    L += _table(["Entity", "Seed", "Required fields"],
                [[e, f"`data/seed/{f}`", _code(bso.REQUIRED[e])] for e, f in bso.ENTITIES.items()])

    L += ["", "## Vocabularies", "", "A value outside its vocabulary is the QC finding `STATUS_VOCAB` (HIGH).",
          "Fields marked derived are stamped by `scripts/classify.py` on every build and never stored in a seed.", ""]
    rows = []
    for entity, fields in qc_gate.VOCAB.items():
        for field, allowed in fields.items():
            rows.append([entity, f"`{field}`" + (" (derived)" if field in qc_gate.DERIVED_FIELDS else ""),
                         _code(sorted(a or "(blank)" for a in allowed))])
    L += _table(["Entity", "Field", "Allowed values"], rows)

    L += ["", "## Restriction severity", "",
          "`build_sabin_seeds.restriction_severity` runs on the mechanisms a row names, its technology, status",
          "and text. Each line below is the rule's own answer for one probe; `severity_basis` is the",
          "text the row carries. A pending instrument is capped at 2.", ""]
    rows = []
    for label, types, tech, status, text in SEVERITY_PROBES:
        score, basis = sabin.restriction_severity(types, tech, status, text)
        rows.append([label, tech, status, score, basis])
    L += _table(["Probe", "Technology", "Status", "Score", "Basis"], rows)
    L += ["", "The mechanism that drives the score names `restriction_type` (`driving_type`). Mechanism",
          "spellings accepted in a review-queue row and the type each maps to:", ""]
    by_type: dict[str, list[str]] = {}
    for spelling, t in sabin.MECHANISM_TYPE.items():
        by_type.setdefault(t, []).append(spelling)
    L += _table(["Type", "Spellings"], [[f"`{t}`", _code(v)] for t, v in sorted(by_type.items())])
    L += ["", f"Non-restricting mechanisms (never scored): {_code(sorted(sabin.NON_RESTRICTING))}.",
          f"Statuses the source may give and the status published: "
          + ", ".join(f"`{k or '(blank)'}` -> `{v}`" for k, v in sabin.RESTRICTION_STATUS.items()) + ".",
          f"Statuses not published (the instrument is not in force): {_code(sorted(sabin.EXCLUDED_STATUS))}; a",
          f"review-queue restriction may carry {_code(pr.QUEUE_RESTRICTION_STATUS)}, of which",
          f"{_code(sorted(pr.NOT_IN_FORCE))} stay in the queue."]

    L += ["", "## Contested projects: outcome and severity", "",
          "A source status maps to an outcome (`build_sabin_seeds.OUTCOME`); a status alone is never",
          "`*_confirmed`. A linked court case decided the same way confirms it (`CONFIRMING_RULING`), as does a",
          "reviewer's resolution whose evidence was opened or archived (`scripts/resolutions.py`).", ""]
    L += _table(["Source status", "Outcome"], [[f"`{k}`", f"`{v}`"] for k, v in sabin.OUTCOME.items()])
    L += [""]
    L += _table(["Unverified outcome", "Confirming case status", "Confirmed outcome"],
                [[f"`{k}`", f"`{v[0]}`", f"`{v[1]}`"] for k, v in sabin.CONFIRMING_RULING.items()])
    L += ["", "`build_sabin_seeds.project_severity(outcome, litigated)`:", ""]
    outcomes = sorted(qc_gate.VOCAB["contested_projects"]["outcome"])
    L += _table(["Outcome", "Not litigated", "Litigated"],
                [[f"`{o}`", sabin.project_severity(o, False), sabin.project_severity(o, True)] for o in outcomes])
    L += ["", f"Finality evidence that satisfies the QC gate: a value starting with "
          f"{_code(qc_gate.FINALITY_PREFIXES)}. `lead: <url>` (a snippet resolution) and `outcome_label_only` "
          "do not."]

    L += ["", "## Derived fields (`scripts/classify.py`)", ""]
    L += _lines([
        f"`evidence_level`, best first: {_code(classify.EVIDENCE_ORDER)}.",
        f"`verification`: {_code(classify.VERIFICATION)}. A restriction is verified only against the instrument "
        "or the minutes that adopted it; opposition activity may rest on a news article that was read.",
        f"`scope` (restrictions): {_code(classify.SCOPES)}. `data_center_only` is quarantined.",
        f"`currency` (restrictions): {_code(classify.CURRENCY)}. In force means status "
        f"{_code(classify.IN_FORCE_STATUSES)} with no end date passed; lapsed_unconfirmed means the end date "
        "passed and no reviewer confirmed the instrument on or after it.",
        "`status_as_of` (restrictions): the latest of an 'as of YYYY-MM-DD' date in the text, the enactment "
        "date, or a reviewer's primary-source check.",
        f"`source_kind` of a queue row: {_code(classify.SOURCE_KINDS)}; only {_code(classify.INSTRUMENT_KINDS)} "
        f"can verify a restriction; {_code(classify.EVENT_KINDS)} can verify a project outcome or event.",
        f"How evidence was seen (`access`): {_code(resolutions.ACCESS)}; only {_code(sorted(resolutions.READ_ACCESS))} "
        f"upgrade a record. Primary-source verdicts: {_code(sorted(resolutions.VERDICTS))}.",
    ])

    L += ["", "## QC checks (`scripts/qc_gate.py`)", "",
          f"A row with any {' or '.join(sorted(qc_gate.BLOCK_AT))} issue is quarantined in "
          "`data/processed/quarantine.json`; lower severities are reported in `data/processed/qc_report.md`.", ""]
    L += _table(["Code", "Severity", "Meaning"], [[f"`{c}`", s, m] for c, s, m in qc_gate.CHECKS])

    L += ["", "## Counting (`scripts/headline_metrics.py`)", ""]
    L += _lines([
        "One instrument counts once, whatever technologies it covers; its severity is the highest of its rows "
        "and its verification the weakest.",
        f"Severe means a severity score in {_code(sorted(hm.SEVERE))}.",
        "Restrictions are split by scope; the headline figure is renewables_only and multi_sector_data_centers is "
        "reported beside it, never folded in.",
        f"Source families: {_code(hm.SOURCES)}.",
    ])

    L += ["", "## Worklists (`scripts/verification_worklist.py`)", "",
          "Outcome tiers, in the order checked, and what would confirm each:", ""]
    L += _table(["Tier", "What would confirm it"], [[f"`{t}`", vw.WHAT_CONFIRMS[t]] for t in vw.OUTCOME_TIERS])
    L += ["", f"Restriction tiers, weakest evidence first: {_code(vw.EVIDENCE_TIERS)}. An instrument whose "
          f"currency is `{vw.LAPSED}` is listed first whatever its tier.", ""]
    L += _lines([
        f"A pending restriction is stale after {vw.STALE_PENDING_DAYS} days (from `status_as_of`).",
        f"A pending project is overdue after {vw.STALE_OUTCOME_DAYS} days (from the latest date in "
        "`event_date_text`, at the end of its precision).",
        f"`decision_language` lists words in a pending row's own text that state a completed decision "
        f"(pattern `{vw.DECISION.pattern}`) unless any word says the step was not final "
        f"(pattern `{vw.NOT_FINAL.pattern}`).",
    ])

    L += ["", "## Negative checks (`scripts/negative_checks.py`)", ""]
    L += _lines([
        f"Scope: {_code(nc.SCOPES)}; result: {_code(nc.RESULTS)}; stale after {nc.STALE_DAYS} days.",
        f"Independence classes of `sources_checked`: {_code([n for n, _ in nc.FAMILIES] + [nc.SECONDARY])}. "
        "A grade counts classes, never sources.",
    ])
    L += [""]
    L += _table(["Grade", "Meaning"], [[f"`{g}`", nc.GRADE_MEANING[g]] for g in nc.GRADES])

    L += ["", "## Promotion trail (`scripts/promote_reviewed.py`)", "",
          "`data/review/promotion_trail.csv` records a decision only when it is new or has changed",
          f"(`scripts/promotion_trail.py`). Columns: {_code(pr.TRAIL_FIELDS)}. Actions: `promoted`, `held`",
          f"(with what the row lacks), `{pr.AWAITING}`, `rejected`, `error`. Review statuses that never promote: "
          f"{_code(sorted(pr.NEVER))}.", ""]
    return "\n".join(L).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/codebook.md is out of date")
    args = ap.parse_args()
    text = render()
    current = CODEBOOK_PATH.read_text(encoding="utf-8") if CODEBOOK_PATH.exists() else ""
    if args.check:
        if current != text:
            print(f"{CODEBOOK_PATH.relative_to(ROOT)} is out of date; run python scripts/codebook.py",
                  file=sys.stderr)
            return 1
        print("codebook: up to date")
        return 0
    if current != text:
        CODEBOOK_PATH.write_text(text, encoding="utf-8")
        print(f"Wrote {CODEBOOK_PATH.relative_to(ROOT)}")
    else:
        print(f"{CODEBOOK_PATH.relative_to(ROOT)} unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
